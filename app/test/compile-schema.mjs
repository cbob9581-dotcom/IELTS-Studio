import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";
const schema = JSON.parse(
  readFileSync(
    new URL("../src/domain/paper.schema.json", import.meta.url),
    "utf8",
  ),
);
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
let source = standaloneCode(ajv, ajv.compile(schema));
// Ajv emits CommonJS runtime references even in ESM output. Resolve them at build time.
const helpers = [];
source = source.replace(
  /require\("(ajv\/dist\/runtime\/[^\"]+)"\)\.default/g,
  (_, path) => {
    const name = `runtimeHelper${helpers.length}`;
    helpers.push(
      `import ${name}Module from '${path}.js'; const ${name}=typeof ${name}Module==='function'?${name}Module:${name}Module.default;`,
    );
    return name;
  },
);
writeFileSync(
  new URL("../src/domain/paper-validator.js", import.meta.url),
  [
    "// Generated by npm run schema. No runtime code generation.",
    ...helpers,
    source,
  ].join("\n"),
);
writeFileSync(
  new URL("../src/domain/paper-validator.d.ts", import.meta.url),
  'import type {ValidateFunction} from "ajv"; declare const validate:ValidateFunction; export default validate;\n',
);
console.log("Compiled static paper validator");
